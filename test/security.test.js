"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const test = require("node:test");
const {
  applyAutoClasses,
  classifyToken,
  generateStylesheet,
  resolveConfig,
  revertProject,
  sanitizeCustomClassName,
} = require("../src");

/**
 * @param {string} prefix
 * @returns {string}
 */
function tempDir(prefix) {
  return fs.mkdtempSync(path.join(os.tmpdir(), `tailclass-${prefix}-`));
}

/**
 * @param {string} dir
 * @param {string} name
 * @param {string} content
 * @returns {string}
 */
function writeFile(dir, name, content) {
  const target = path.join(dir, name);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content, "utf8");
  return target;
}

/**
 * @param {string} file
 * @returns {string}
 */
function read(file) {
  return fs.readFileSync(file, "utf8");
}

const NAV = "sticky top-0 flex items-center justify-between bg-white px-6 py-4 border-b border-slate-200";
const NAV_HTML = `<nav class="${NAV}">home</nav>\n<nav class="${NAV}">about</nav>\n`;

test("config files cannot redirect generated output outside the project root", () => {
  const dir = tempDir("traversal");
  const site = path.join(dir, "site");
  fs.mkdirSync(site);
  writeFile(site, "index.html", NAV_HTML);

  for (const key of ["outputCss", "manifestFile", "dictionaryFile"]) {
    writeFile(site, "tailclass.config.json", JSON.stringify({ [key]: "../escaped.css" }));
    assert.throws(
      () => resolveConfig(site),
      /must stay inside the project root/,
      `${key} should be confined to the project root`
    );
    assert.throws(() => applyAutoClasses(site), /must stay inside the project root/);
  }

  assert.equal(fs.existsSync(path.join(dir, "escaped.css")), false);
  assert.match(read(path.join(site, "index.html")), /<nav class="sticky/, "sources must be untouched");

  // Paths explicitly typed on the command line remain the caller's prerogative.
  writeFile(site, "tailclass.config.json", "{}");
  const cliConfig = resolveConfig(site, { outputCss: "../explicit.css" });
  assert.equal(cliConfig.outputCss, "../explicit.css");
});

test("apply refuses to point generated output at a source file", () => {
  const dir = tempDir("clobber");
  writeFile(dir, "tailclass.config.json", JSON.stringify({ outputCss: "page.html" }));
  writeFile(dir, "page.html", NAV_HTML);

  // `outputCss`/`manifestFile` are auto-excluded from the scan, so the guard that
  // fires here is the "does not look like TailClass output" one; the
  // scanned-source guard exists as defence in depth for hand-built configs.
  assert.throws(() => applyAutoClasses(dir), /Refusing to overwrite the existing stylesheet/);
  assert.match(read(path.join(dir, "page.html")), /<nav class="sticky/);
});

test("apply refuses to clobber a stylesheet it does not own unless --force is used", () => {
  const dir = tempDir("foreign-css");
  writeFile(dir, "tailclass.config.json", JSON.stringify({ outputCss: "styles.css" }));
  writeFile(dir, "styles.css", "body { color: red; }\n");
  writeFile(dir, "index.html", NAV_HTML);

  assert.throws(() => applyAutoClasses(dir), /does not look like TailClass output/);
  assert.equal(read(path.join(dir, "styles.css")), "body { color: red; }\n");

  applyAutoClasses(dir, { force: true });
  assert.match(read(path.join(dir, "styles.css")), /Generated by TailClass/);
});

test("CSS-breaking utility tokens are kept inline instead of being written into @apply", () => {
  const dir = tempDir("css-injection");
  const evil = "text-[red;}html{display:none}]";
  writeFile(
    dir,
    "index.html",
    `<div class="p-4 bg-white rounded ${evil} flex items-center gap-2">a</div>\n` +
      `<div class="p-4 bg-white rounded ${evil} flex items-center gap-2">b</div>\n`
  );

  applyAutoClasses(dir);

  const css = read(path.join(dir, "tailclass.css"));
  assert.ok(!css.includes("display:none"), `@apply must not contain injected rules:\n${css}`);
  assert.ok(!css.includes("html{"), "no injected selector should reach the stylesheet");
  assert.match(css, /@apply flex items-center gap-2 p-4 bg-white rounded;/);

  const html = read(path.join(dir, "index.html"));
  assert.ok(html.includes(evil), "the unsafe token must be preserved inline on the element");
  assert.equal((html.match(/display:none/g) || []).length, 2);
});

test("dictionary labels, categories and element hints cannot break out of generated comments", () => {
  const dir = tempDir("dict-injection");
  writeFile(dir, "index.html", NAV_HTML);
  writeFile(
    dir,
    "tailclass.map.json",
    JSON.stringify({
      mappings: [
        {
          autoName: "evil",
          customName: "evil",
          classes: "p-6 shadow-lg",
          category: "x */ body{display:none} /*",
          label: "y */ body{display:none} /*",
          elements: ["div", "*/body{color:red}"],
          enabled: true,
        },
      ],
    })
  );

  applyAutoClasses(dir, { ignoreDictionary: false });

  const css = read(path.join(dir, "tailclass.css"));
  assert.ok(!css.includes("body{display:none}"), `dictionary label must be escaped:\n${css}`);
  assert.ok(!/body\s*\{\s*color/.test(css), "element hints must be sanitized");
  assert.match(css, /^@layer components \{/m);
});

test(".classifier never marks CSS-unsafe tokens as applyable", () => {
  for (const token of ["p-4;color:red", "bg-[red}]", "[mask-type:luminance}", "a*/b"]) {
    const info = classifyToken(token);
    assert.equal(info.isApplyable, false, `${token} must not be applyable`);
    assert.equal(info.isTailwind, false, `${token} must not count as a Tailwind utility`);
  }
  // Safe arbitrary values still classify normally.
  assert.equal(classifyToken("grid-cols-[240px_1fr]").isApplyable, true);
  assert.equal(classifyToken("[mask-type:luminance]").isApplyable, true);
});

test("generator skips mappings whose selector or @apply payload is unsafe", () => {
  const css = generateStylesheet([
    {
      finalName: "bad name{color:red}",
      canonicalKey: "p-4 flex",
      category: "layout",
      label: "Bad",
      elements: ["div"],
      timesFound: 2,
      fileCount: 1,
    },
    {
      finalName: "good-name",
      canonicalKey: "p-4;color:red",
      category: "layout",
      label: "Good",
      elements: ["div"],
      timesFound: 2,
      fileCount: 1,
    },
  ]);
  assert.ok(!css.includes("bad name"), css);
  assert.ok(!css.includes("color:red"), css);
  assert.ok(css.includes("Skipped unsafe class name"), "skips should be visible in the output");
});

test("invalid classPrefix values are rejected with a clear error", () => {
  const dir = tempDir("prefix");
  writeFile(dir, "index.html", NAV_HTML);
  for (const classPrefix of ["ui-}body{display:none}/*", "9-", "-3d"]) {
    assert.throws(
      () => resolveConfig(dir, { classPrefix }),
      /Invalid classPrefix/,
      `prefix ${classPrefix} should be rejected`
    );
  }
  assert.equal(resolveConfig(dir, { classPrefix: "ui-" }).classPrefix, "ui-");
});

test("numeric custom class names are prefixed so selectors stay valid", () => {
  assert.equal(sanitizeCustomClassName("123btn"), "tc-123btn");
  assert.equal(sanitizeCustomClassName("-3d"), "tc--3d");
  assert.equal(sanitizeCustomClassName("btn-primary"), "btn-primary");
});

test("configuration errors name the offending key instead of leaking internals", () => {
  const dir = tempDir("bad-config");
  writeFile(dir, "index.html", NAV_HTML);

  writeFile(dir, "tailclass.config.json", '{"exclude": [}');
  assert.throws(() => resolveConfig(dir), /Invalid JSON in .*tailclass\.config\.json/);

  writeFile(dir, "tailclass.config.json", JSON.stringify({ exclude: ["dist/**", null, 42] }));
  assert.throws(() => resolveConfig(dir), /Invalid exclude\[1\]: expected a string, received null/);

  writeFile(dir, "tailclass.config.json", JSON.stringify({ minClasses: "lots" }));
  assert.throws(() => resolveConfig(dir), /Invalid minClasses/);

  writeFile(dir, "tailclass.config.json", JSON.stringify({ outputCss: "../../escape.css" }));
  assert.throws(() => resolveConfig(dir), /must stay inside the project root/);
});

test("unknown config keys surface as warnings without failing the run", () => {
  const dir = tempDir("warnings");
  writeFile(dir, "index.html", NAV_HTML);
  writeFile(dir, "tailclass.config.json", JSON.stringify({ minOccurrencess: 3 }));

  const config = resolveConfig(dir);
  assert.ok(config.warnings.some((w) => w.includes("minOccurrencess")));
  assert.equal(applyAutoClasses(dir).totalFilesModified, 1);
});

test("revert ignores manifest entries whose expansion could corrupt markup", () => {
  const dir = tempDir("revert-manifest");
  writeFile(
    dir,
    "index.html",
    '<div class="tc-good p-1">a</div>\n<div class="tc-evil p-1">b</div>\n'
  );
  writeFile(
    dir,
    ".tailclass-manifest.json",
    JSON.stringify({
      version: "1.0.1",
      mappings: {
        "tc-good": "flex p-4 m-2",
        "tc-evil": 'p-4" onmouseover="alert(1)',
        "bad key{": "flex",
      },
    })
  );

  revertProject(dir);

  const html = read(path.join(dir, "index.html"));
  assert.ok(!html.includes("onmouseover"), html);
  assert.ok(!html.includes("bad key{"), html);
  assert.match(html, /class="flex p-4 m-2 p-1"/);
});

test("a corrupt manifest produces a descriptive error", () => {
  const dir = tempDir("bad-manifest");
  writeFile(dir, "index.html", NAV_HTML);
  writeFile(dir, ".tailclass-manifest.json", "{ not json");
  assert.throws(() => revertProject(dir), /Invalid manifest .*tailclass-manifest\.json/);
});
