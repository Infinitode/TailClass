"use strict";

const CATEGORY_TITLES = {
  navigation: "Navigation & Headers",
  layout: "Page Layout & Containers",
  surfaces: "Cards & Surface Panels",
  controls: "Buttons & Interactive Controls",
  forms: "Forms & Inputs",
  "data-display": "Badges, Tables & Media",
  typography: "Typography",
  overlay: "Modals & Overlays",
  feedback: "Alerts & Loading States",
  components: "Components",
  custom: "Custom Mapped Classes",
};

const CATEGORY_ORDER = [
  "navigation",
  "layout",
  "surfaces",
  "controls",
  "forms",
  "data-display",
  "typography",
  "overlay",
  "feedback",
  "components",
  "custom",
];

/**
 * Parse an existing TailClass stylesheet (or any CSS file containing simple
 * `.class-name { @apply ...; }` rules) to preserve previously extracted classes
 * across incremental runs and enable manifest-free reverts.
 *
 * @param {string} cssText
 * @returns {Map<string, string>} Map of `className -> utilitiesString`
 */
function parseExistingStylesheet(cssText) {
  const map = new Map();
  if (!cssText || typeof cssText !== "string") return map;

  // Strip block comments before parsing selectors
  const uncommented = cssText.replace(/\/\*[\s\S]*?\*\//g, "");

  // Match `.className { @apply ...; }` and Tailwind v4 `@utility className { @apply ...; }`
  const ruleRe = /(?:\.([a-zA-Z0-9_-]+)|@utility\s+([a-zA-Z0-9_-]+))\s*\{\s*@apply\s+([^;{}]+);?\s*\}/g;
  let match;
  while ((match = ruleRe.exec(uncommented)) !== null) {
    const className = match[1] || match[2];
    const utilities = match[3].trim().replace(/\s+/g, " ");
    if (className && utilities) {
      map.set(className, utilities);
    }
  }

  return map;
}

/**
 * Generate the centralized Tailwind CSS stylesheet from resolved active mappings.
 *
 * @param {Array<object>} activeMappings
 * @param {{
 *   cssFormat?: "tailwind-v3" | "tailwind-v4" | "plain",
 *   comments?: boolean,
 *   groupByCategory?: boolean,
 *   version?: string
 * }} [config]
 * @returns {string}
 */
function generateStylesheet(activeMappings, config = {}) {
  const format = config.cssFormat || "tailwind-v3";
  const showComments = config.comments !== false;
  const groupByCategory = config.groupByCategory !== false;
  const version = config.version || "1.0.0";

  const lines = [];

  if (showComments) {
    lines.push(
      `/* Generated by TailClass v${version} — https://github.com/Infinitode/TailClass */`,
      `/* Centralized Tailwind component classes. Edit rules here to update styles site-wide. */`
    );
    if (format === "tailwind-v4") {
      lines.push(
        `/* Tailwind CSS v4: import this file after \`@import "tailwindcss";\` in your main stylesheet. */`
      );
    }
    lines.push("");
  }

  if (!activeMappings || activeMappings.length === 0) {
    if (format === "tailwind-v3") {
      lines.push("@layer components {\n  /* No repeated patterns matched thresholds. */\n}\n");
    } else {
      lines.push("/* No repeated patterns matched thresholds. */\n");
    }
    return lines.join("\n");
  }

  const orderedGroups = groupMappings(activeMappings, groupByCategory);

  if (format === "tailwind-v3") {
    lines.push("@layer components {");
    emitGroups(lines, orderedGroups, { indent: "  ", showComments, useUtilityDirective: false });
    lines.push("}", "");
    return lines.join("\n");
  }

  if (format === "tailwind-v4") {
    lines.push("@layer components {");
    emitGroups(lines, orderedGroups, { indent: "  ", showComments, useUtilityDirective: false });
    lines.push("}", "");
    return lines.join("\n");
  }

  // "plain" format: direct `.class { @apply ...; }` rules
  emitGroups(lines, orderedGroups, { indent: "", showComments, useUtilityDirective: false });
  return lines.join("\n");
}

function groupMappings(activeMappings, groupByCategory) {
  if (!groupByCategory) {
    return [{ category: null, title: null, items: activeMappings }];
  }

  const buckets = new Map();
  for (const m of activeMappings) {
    const cat = m.category || "layout";
    if (!buckets.has(cat)) buckets.set(cat, []);
    buckets.get(cat).push(m);
  }

  const groups = [];
  for (const cat of CATEGORY_ORDER) {
    if (buckets.has(cat)) {
      groups.push({
        category: cat,
        title: CATEGORY_TITLES[cat] || cat,
        items: buckets.get(cat),
      });
      buckets.delete(cat);
    }
  }
  for (const [cat, items] of buckets.entries()) {
    groups.push({
      category: cat,
      title: CATEGORY_TITLES[cat] || cat,
      items,
    });
  }
  return groups;
}

function emitGroups(lines, groups, { indent, showComments, useUtilityDirective }) {
  let firstSection = true;

  for (const group of groups) {
    if (!firstSection) lines.push("");
    firstSection = false;

    if (showComments && group.title) {
      lines.push(`${indent}/* === ${group.title} === */`);
    }

    for (let i = 0; i < group.items.length; i++) {
      const m = group.items[i];
      if (i > 0) lines.push("");

      if (showComments) {
        const elemHint =
          Array.isArray(m.elements) && m.elements.length > 0
            ? ` (${m.elements.map((e) => `<${e}>`).join(", ")})`
            : "";
        const countHint =
          typeof m.timesFound === "number" && m.timesFound > 0
            ? ` — ${m.timesFound} occurrence${m.timesFound === 1 ? "" : "s"} across ${m.fileCount || 1} file${(m.fileCount || 1) === 1 ? "" : "s"}`
            : "";
        const label = m.label || m.finalName;
        lines.push(`${indent}/* ${label}${countHint}${elemHint} */`);
      }

      const selector = useUtilityDirective ? `@utility ${m.finalName}` : `.${m.finalName}`;
      lines.push(`${indent}${selector} {`);
      lines.push(`${indent}  @apply ${m.canonicalKey};`);
      lines.push(`${indent}}`);
    }
  }
}

module.exports = {
  CATEGORY_TITLES,
  parseExistingStylesheet,
  generateStylesheet,
};
