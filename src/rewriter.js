"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { checkSubsetCompatibility, computePatternId } = require("./analyzer");
const { isValidClassIdentifier } = require("./css-safety");
const {
  resolveWritablePath,
  unlinkResolvedFile,
  writeResolvedFile,
} = require("./config");
const { writeFileNoFollow } = require("./fs-safety");
const { generateStylesheet, parseExistingStylesheet } = require("./generator");
const { toPosixPath } = require("./glob");
const { scanSource } = require("./scanner");
const { partitionAndCanonicalize, splitClassTokens } = require("./tailwind");
const { VERSION } = require("./version");

/** Marker written into every generated stylesheet header. */
const GENERATED_CSS_MARKER = "Generated by TailClass";

/**
 * Validate a utility expansion coming from a manifest / stylesheet before it is
 * written back into markup. Expansions are single tokens from repository files,
 * so quotes that could terminate an HTML attribute are rejected.
 * @param {unknown} value
 * @returns {boolean}
 */
function isSafeExpansion(value) {
  if (typeof value !== "string" || value.trim() === "") return false;
  // eslint-disable-next-line no-control-regex
  return !/["<>`\u0000-\u001f\u007f]/.test(value);
}

/**
 * @param {string} filePath
 * @returns {string | null}
 */
function safeReadText(filePath) {
  try {
    return fs.readFileSync(filePath, "utf8");
  } catch {
    return null;
  }
}

/**
 * Heuristic: is this file a TailClass generated stylesheet (or harmless to replace)?
 * @param {string} content
 * @returns {boolean}
 */
function cssLooksGenerated(content) {
  if (typeof content !== "string") return false;
  if (content.trim() === "") return true;
  if (content.includes(GENERATED_CSS_MARKER)) return true;
  try {
    return parseExistingStylesheet(content).size > 0;
  } catch {
    return false;
  }
}

/**
 * Heuristic: is this file a TailClass revert manifest?
 * @param {string} content
 * @returns {boolean}
 */
function manifestLooksGenerated(content) {
  if (typeof content !== "string") return false;
  if (content.trim() === "") return true;
  try {
    const parsed = JSON.parse(content);
    return Boolean(parsed && typeof parsed === "object" && typeof parsed.mappings === "object");
  } catch {
    return false;
  }
}

/** Top-level keys ever written into a TailClass revert manifest. */
const MANIFEST_KEYS = new Set([
  "generator",
  "version",
  "updatedAt",
  "generatedAt",
  "outputCss",
  "manifestPath",
  "filesModified",
  "mappings",
  "$schema",
]);

/**
 * Strict ownership check used before `--clean` deletes anything.
 *
 * `manifestLooksGenerated` is intentionally lenient (it decides whether a file
 * may be *overwritten*). Deletion is irreversible, so a file only counts as a
 * TailClass manifest when it carries our version/generator marker and a
 * plausible `mappings` record. A random JSON file that happens to have a
 * `mappings` key is not enough.
 *
 * @param {unknown} value
 * @returns {boolean}
 */
function isTailClassManifestObject(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  // A file belonging to another tool (package.json, a source map, ...) may also
  // have `version`/`mappings`; its extra keys make it clearly not ours.
  if (Object.keys(value).some((key) => !MANIFEST_KEYS.has(key))) return false;
  const marked =
    value.generator === "TailClass" ||
    (typeof value.version === "string" && /^\d+\.\d+\.\d+/.test(value.version));
  if (!marked) return false;
  const mappings = value.mappings;
  if (!mappings || typeof mappings !== "object" || Array.isArray(mappings)) return false;
  const entries = Object.entries(mappings);
  // A run with no extracted patterns still produces an (empty) owned manifest.
  if (entries.length === 0) return true;
  return entries.some(
    ([name, utilities]) => isValidClassIdentifier(name) && isSafeExpansion(utilities)
  );
}

/**
 * @param {string} text
 * @returns {string}
 */
function normalizeUtilities(text) {
  if (typeof text !== "string") return "";
  return splitClassTokens(text).sort().join(" ");
}

/**
 * Decide whether a stylesheet may be deleted by `revert --clean`.
 *
 * A generated stylesheet is recognised by its header marker. When comments were
 * disabled (`--no-comments`) there is no header, so every `@apply` rule must
 * instead match the class → utilities record in an owned revert manifest.
 * Foreign CSS (including CSS that merely contains a few `@apply` rules) is
 * never deleted.
 *
 * @param {string} cssText
 * @param {unknown} manifest parsed manifest object, or null
 * @returns {boolean}
 */
function stylesheetIsOwned(cssText, manifest) {
  if (typeof cssText !== "string" || cssText.trim() === "") return false;
  let rules;
  try {
    rules = parseExistingStylesheet(cssText);
  } catch {
    return false;
  }
  if (!rules || rules.size === 0) return false;

  // Require the real generated header (with its version), not just a stray
  // mention of the tool name inside someone else's stylesheet.
  const hasMarker = /\/\*\s*Generated by TailClass v\d+\.\d+\.\d+/.test(cssText);
  const mappings = isTailClassManifestObject(manifest) ? manifest.mappings : null;
  if (!hasMarker && !mappings) return false;

  for (const [name, utilities] of rules) {
    if (!isValidClassIdentifier(name) || !isSafeExpansion(utilities)) return false;
    if (!hasMarker) {
      const expected = mappings[name];
      if (
        typeof expected !== "string" ||
        normalizeUtilities(expected) !== normalizeUtilities(utilities)
      ) {
        return false;
      }
    }
  }
  return true;
}

/**
 * Read a file only when it is safe to treat as TailClass output.
 * @param {string} filePath
 * @param {(content: string) => boolean} isCompatible
 * @param {{ force?: boolean, label: string, hint?: string }} options
 * @returns {string | null} existing content (when present and compatible)
 */
function readIfCompatible(filePath, isCompatible, options) {
  if (!fs.existsSync(filePath)) return null;
  let content = null;
  try {
    content = fs.readFileSync(filePath, "utf8");
  } catch {
    content = null;
  }
  if (options.force) return content;
  if (content !== null && isCompatible(content)) return content;
  throw new Error(
    `Refusing to overwrite ${options.label} at ${filePath}: it does not look like TailClass output. ` +
      (options.hint || "Move it, pick another path, or re-run with --force.")
  );
}

/**
 * Merge previously extracted CSS rules from an existing `tailclass.css` into
 * `activeMappings` so incremental runs are idempotent, preserve previously
 * extracted component classes, and rewrite newly added pages consistently.
 *
 * @param {Array<object>} activeMappings
 * @param {Map<string, string>} existingCssRules
 * @param {Record<string, any>} [config]
 * @returns {Array<object>}
 */
function mergeWithExistingCssRules(activeMappings, existingCssRules, config = {}) {
  if (!existingCssRules || existingCssRules.size === 0) {
    return activeMappings;
  }

  const byCanonical = new Map();
  const usedNames = new Set();

  for (const m of activeMappings) {
    byCanonical.set(m.canonicalKey, m);
    usedNames.add(m.finalName);
  }

  const merged = [...activeMappings];

  for (const [existingName, rawUtilities] of existingCssRules.entries()) {
    const part = partitionAndCanonicalize(rawUtilities, {
      tailwindPrefix: config.tailwindPrefix || "",
    });
    if (!part.canonicalKey) continue;
    if (!isValidClassIdentifier(existingName)) continue;

    if (byCanonical.has(part.canonicalKey)) {
      const current = byCanonical.get(part.canonicalKey);
      // Keep existing CSS class name unless the user explicitly supplied a custom dictionary override
      if (current.nameSource !== "dictionary" && current.finalName !== existingName) {
        if (!usedNames.has(existingName)) {
          usedNames.delete(current.finalName);
          current.finalName = existingName;
          current.autoName = existingName;
          usedNames.add(existingName);
        }
      }
      continue;
    }

    if (!usedNames.has(existingName)) {
      const propGroups = new Set(part.applyableInfos.map((i) => i.propertyGroup));
      const preserved = {
        id: computePatternId(part.canonicalKey),
        canonicalKey: part.canonicalKey,
        canonicalTokens: part.canonicalTokens,
        propGroups,
        classCount: part.canonicalTokens.length,
        timesFound: 0,
        exactMatches: 0,
        subsetMatches: 0,
        fileCount: 0,
        files: [],
        elements: [],
        occurrences: [],
        qualifies: true,
        autoName: existingName,
        finalName: existingName,
        customName: "",
        category: "components",
        label: existingName,
        confidence: 1,
        nameSource: "existing-css",
      };
      merged.push(preserved);
      byCanonical.set(part.canonicalKey, preserved);
      usedNames.add(existingName);
    }
  }

  return merged;
}

/**
 * Rewrite a single file's source string in memory using `activeMappings`.
 *
 * @param {string} source
 * @param {string} filePath
 * @param {Array<object>} activeMappings
 * @param {Record<string, any>} [config]
 */
function rewriteSource(source, filePath, activeMappings, config = {}) {
  const relFile = toPosixPath(filePath);
  const scanned = scanSource(source, relFile, config);
  const subsetMatching = config.subsetMatching !== false;
  const subsetMinClasses = Math.max(2, Number(config.subsetMinClasses) || 4);

  const exactLookup = new Map();
  const preparedMappings = [];

  for (const m of activeMappings || []) {
    if (!m || !m.canonicalKey || !m.finalName) continue;
    // A mapping whose final name is not a valid CSS class selector would emit
    // broken (or injectable) selectors and attributes.
    if (!isValidClassIdentifier(m.finalName)) continue;
    const propGroups =
      m.propGroups instanceof Set
        ? m.propGroups
        : new Set(
            partitionAndCanonicalize(m.canonicalKey, {
              tailwindPrefix: config.tailwindPrefix || "",
            }).applyableInfos.map((i) => i.propertyGroup)
          );
    const enriched = {
      ...m,
      canonicalTokens: m.canonicalTokens || splitClassTokens(m.canonicalKey),
      propGroups,
    };
    exactLookup.set(enriched.canonicalKey, enriched);
    preparedMappings.push(enriched);
  }

  // Prefer largest patterns first for subset matching
  preparedMappings.sort((a, b) => b.canonicalTokens.length - a.canonicalTokens.length);

  const edits = [];

  for (const occ of scanned.occurrences) {
    if (occ.canonicalTokens.length === 0) continue;

    let chosen = null;
    let residualTokens = [];
    let isExact = false;

    // 1. Exact canonical match
    if (exactLookup.has(occ.canonicalKey)) {
      chosen = exactLookup.get(occ.canonicalKey);
      isExact = true;
    } else if (subsetMatching) {
      // 2. Conflict-free subset match
      for (const candidate of preparedMappings) {
        const minReq =
          candidate.nameSource === "dictionary" || candidate.nameSource === "existing-css"
            ? Math.max(2, Number(config.minClasses) || 3)
            : subsetMinClasses;
        if (candidate.canonicalTokens.length < minReq) continue;

        const compat = checkSubsetCompatibility(
          candidate.canonicalTokens,
          candidate.propGroups,
          occ
        );
        if (compat.matches) {
          chosen = candidate;
          residualTokens = compat.residualTokens;
          isExact = compat.isExact;
          break;
        }
      }
    }

    if (!chosen) continue;

    // Deduplicate tokens while keeping semantic class first, then residual utilities, then inline hooks (`group`, `js-*`)
    const nextTokens = [];
    const seen = new Set();
    for (const tok of [chosen.finalName, ...residualTokens, ...occ.inlineTokens]) {
      if (tok && !seen.has(tok)) {
        seen.add(tok);
        nextTokens.push(tok);
      }
    }

    const replacementSlice = `${occ.leadingWs}${nextTokens.join(" ")}${occ.trailingWs}`;
    if (replacementSlice === occ.rawValue) continue;

    edits.push({
      line: occ.line,
      column: occ.column,
      valueStart: occ.valueStart,
      valueEnd: occ.valueEnd,
      before: occ.rawValue,
      after: replacementSlice,
      appliedClass: chosen.finalName,
      patternId: chosen.id,
      isExact,
    });
  }

  if (edits.length === 0) {
    return {
      file: relFile,
      changed: false,
      output: source,
      edits: [],
      replacementsCount: 0,
      bytesSaved: 0,
    };
  }

  // Apply non-overlapping edits from back to front so offsets stay exact
  const descending = [...edits].sort((a, b) => b.valueStart - a.valueStart);
  let output = source;
  let lastStart = Infinity;

  for (const edit of descending) {
    if (edit.valueEnd > lastStart) continue;
    output = output.slice(0, edit.valueStart) + edit.after + output.slice(edit.valueEnd);
    lastStart = edit.valueStart;
  }

  return {
    file: relFile,
    changed: output !== source,
    output,
    edits,
    replacementsCount: edits.length,
    bytesSaved: Buffer.byteLength(source, "utf8") - Buffer.byteLength(output, "utf8"),
  };
}

/**
 * Expand centralized TailClass names in a source string back into their
 * original inline Tailwind CSS utilities.
 *
 * @param {string} source
 * @param {string} filePath
 * @param {Map<string, string> | Record<string, string>} classToUtilities
 * @param {Record<string, any>} [config]
 */
function revertSource(source, filePath, classToUtilities, config = {}) {
  const relFile = toPosixPath(filePath);
  const map =
    classToUtilities instanceof Map
      ? classToUtilities
      : new Map(Object.entries(classToUtilities || {}));

  if (map.size === 0) {
    return { file: relFile, changed: false, output: source, edits: [], revertedCount: 0 };
  }

  const scanned = scanSource(source, relFile, {
    ...config,
    excludePatterns: [],
    ignoreTags: ["script", "style"],
    onlyTags: [],
  });

  const edits = [];

  for (const occ of scanned.occurrences) {
    const rawTokens = splitClassTokens(occ.rawValue);
    let touched = false;
    const expanded = [];
    const seen = new Set();

    for (const tok of rawTokens) {
      if (map.has(tok)) {
        touched = true;
        for (const u of splitClassTokens(map.get(tok))) {
          if (!seen.has(u)) {
            seen.add(u);
            expanded.push(u);
          }
        }
      } else if (!seen.has(tok)) {
        seen.add(tok);
        expanded.push(tok);
      }
    }

    if (!touched) continue;

    const after = `${occ.leadingWs}${expanded.join(" ")}${occ.trailingWs}`;
    if (after === occ.rawValue) continue;

    edits.push({
      line: occ.line,
      column: occ.column,
      valueStart: occ.valueStart,
      valueEnd: occ.valueEnd,
      before: occ.rawValue,
      after,
    });
  }

  if (edits.length === 0) {
    return { file: relFile, changed: false, output: source, edits: [], revertedCount: 0 };
  }

  const descending = [...edits].sort((a, b) => b.valueStart - a.valueStart);
  let output = source;
  let lastStart = Infinity;

  for (const edit of descending) {
    if (edit.valueEnd > lastStart) continue;
    output = output.slice(0, edit.valueStart) + edit.after + output.slice(edit.valueEnd);
    lastStart = edit.valueStart;
  }

  return {
    file: relFile,
    changed: output !== source,
    output,
    edits,
    revertedCount: edits.length,
  };
}

/**
 * Apply resolved class mappings across a scanned project directory, write the
 * centralized CSS stylesheet, and save the revert manifest (unless `dryRun` is true).
 *
 * @param {object} scanResult
 * @param {Array<object>} resolvedMappings
 * @param {Record<string, any>} config
 * @param {{ dryRun?: boolean, backup?: boolean, version?: string }} [runOptions]
 */
function applyMappingsToProject(scanResult, resolvedMappings, config, runOptions = {}) {
  const absRoot = scanResult.rootDir;
  const dryRun = Boolean(runOptions.dryRun);
  const backup = Boolean(runOptions.backup);
  const force = Boolean(runOptions.force);
  const outputCssPath = resolveWritablePath(
    absRoot,
    config.outputCss || "tailclass.css",
    "outputCss",
    config
  );
  const manifestPath = resolveWritablePath(
    absRoot,
    config.manifestFile || ".tailclass-manifest.json",
    "manifestFile",
    config
  );

  // Never let the generated stylesheet or manifest clobber a file that is part of
  // the scanned sources (e.g. `"outputCss": "src/index.html"`).
  const scannedRelPaths = new Set((scanResult.filesScanned || []).map((f) => toPosixPath(f)));
  for (const [key, target] of [
    ["outputCss", outputCssPath],
    ["manifestFile", manifestPath],
  ]) {
    const rel = toPosixPath(path.relative(absRoot, target));
    if (scannedRelPaths.has(rel)) {
      throw new Error(
        `Refusing to overwrite scanned source file "${rel}" with the ${key} output. ` +
          `Choose a different path (for example "tailclass.css").`
      );
    }
  }

  let existingCssText = null;
  if (fs.existsSync(outputCssPath)) {
    existingCssText = dryRun
      ? safeReadText(outputCssPath)
      : readIfCompatible(outputCssPath, cssLooksGenerated, {
          force,
          label: "the existing stylesheet",
          hint: 'Point "outputCss" at a TailClass-owned file (default: tailclass.css) or re-run with --force.',
        });
  }

  let existingCssRules = new Map();
  if (existingCssText) {
    try {
      existingCssRules = parseExistingStylesheet(existingCssText);
    } catch {
      // Ignore unreadable prior stylesheet
    }
  }

  // Fail fast: verify the manifest is ours before any source file is rewritten.
  if (!dryRun) {
    readIfCompatible(manifestPath, manifestLooksGenerated, {
      force,
      label: "the existing manifest",
      hint: 'Point "manifestFile" at a TailClass manifest (default: .tailclass-manifest.json) or re-run with --force.',
    });
  }

  const finalMappings = mergeWithExistingCssRules(resolvedMappings, existingCssRules, config);

  // Track real applied counts across files
  const appliedCountByClass = new Map();
  const appliedFilesByClass = new Map();

  const fileEdits = [];
  let totalReplacements = 0;
  let totalBytesSaved = 0;

  for (const relFile of scanResult.filesScanned) {
    const fullPath = path.join(absRoot, relFile);
    let source;
    try {
      source = fs.readFileSync(fullPath, "utf8");
    } catch {
      continue;
    }
    if (source.includes("\u0000")) continue;

    const res = rewriteSource(source, relFile, finalMappings, config);
    if (!res.changed) continue;

    fileEdits.push(res);
    totalReplacements += res.replacementsCount;
    totalBytesSaved += res.bytesSaved;

    for (const edit of res.edits) {
      appliedCountByClass.set(
        edit.appliedClass,
        (appliedCountByClass.get(edit.appliedClass) || 0) + 1
      );
      if (!appliedFilesByClass.has(edit.appliedClass)) {
        appliedFilesByClass.set(edit.appliedClass, new Set());
      }
      appliedFilesByClass.get(edit.appliedClass).add(relFile);
    }

    if (!dryRun) {
      if (backup) {
        const backupDest = path.join(absRoot, ".tailclass-backup", relFile);
        // `.tailclass-backup/` is repository content too: make sure a symlink
        // there cannot redirect backups outside the project.
        const checkedBackup = resolveWritablePath(
          absRoot,
          path.relative(absRoot, backupDest),
          "backupFile",
          config
        );
        fs.mkdirSync(path.dirname(checkedBackup), { recursive: true });
        resolveWritablePath(absRoot, checkedBackup, "backupFile", config);
        writeFileNoFollow(checkedBackup, source);
      }
      writeFileNoFollow(fullPath, res.output);
    }
  }

  // Update metadata counts for accurate CSS header comments
  for (const m of finalMappings) {
    const newlyApplied = appliedCountByClass.get(m.finalName) || 0;
    if (newlyApplied > m.timesFound) {
      m.timesFound = newlyApplied;
    }
    const fSet = appliedFilesByClass.get(m.finalName);
    if (fSet && fSet.size > (m.fileCount || 0)) {
      m.fileCount = fSet.size;
    }
  }

  const cssContent = generateStylesheet(finalMappings, {
    cssFormat: config.cssFormat,
    comments: config.comments,
    groupByCategory: config.groupByCategory,
    version: runOptions.version || VERSION,
  });

  if (!dryRun) {
    writeResolvedFile(absRoot, outputCssPath, "outputCss", config, cssContent);

    const mappingRecord = {};
    for (const m of finalMappings) {
      mappingRecord[m.finalName] = m.canonicalKey;
    }

    const manifestPayload = {
      generator: "TailClass",
      version: runOptions.version || VERSION,
      updatedAt: new Date().toISOString(),
      outputCss: toPosixPath(path.relative(absRoot, outputCssPath)),
      manifestPath: toPosixPath(path.relative(absRoot, manifestPath)),
      filesModified: fileEdits.map((f) => f.file),
      mappings: mappingRecord,
    };

    writeResolvedFile(
      absRoot,
      manifestPath,
      "manifestFile",
      config,
      JSON.stringify(manifestPayload, null, 2) + "\n"
    );
  }

  return {
    dryRun,
    outputCssPath,
    manifestPath,
    cssContent,
    activeMappings: finalMappings,
    filesModified: fileEdits,
    totalFilesModified: fileEdits.length,
    totalReplacements,
    totalBytesSaved,
  };
}

/**
 * Revert centralized TailClass classes across a project back to inline Tailwind
 * utilities using `.tailclass-manifest.json` and/or `tailclass.css`.
 *
 * `clean` only ever deletes files that TailClass can positively identify as its
 * own output. `--force` never relaxes that rule: deleting a foreign stylesheet,
 * manifest or source file is irreversible and is not needed to complete a revert.
 *
 * @param {string} rootDir
 * @param {Record<string, any>} config
 * @param {{ dryRun?: boolean, clean?: boolean, force?: boolean, filesScanned?: string[] }} [options]
 */
function revertProjectFiles(rootDir, config, options = {}) {
  const absRoot = path.resolve(rootDir || ".");
  const dryRun = Boolean(options.dryRun);
  const clean = Boolean(options.clean);
  const manifestPath = resolveWritablePath(
    absRoot,
    config.manifestFile || ".tailclass-manifest.json",
    "manifestFile",
    config
  );
  const outputCssPath = resolveWritablePath(
    absRoot,
    config.outputCss || "tailclass.css",
    "outputCss",
    config
  );

  const classToUtilities = new Map();

  let manifest = null;
  let manifestOwned = false;
  if (fs.existsSync(manifestPath)) {
    let raw;
    try {
      raw = fs.readFileSync(manifestPath, "utf8");
    } catch (err) {
      throw new Error(`Invalid manifest ${manifestPath}: ${err.message}`);
    }
    try {
      manifest = JSON.parse(raw);
    } catch (err) {
      throw new Error(`Invalid manifest ${manifestPath}: ${err.message}`);
    }
    manifestOwned = isTailClassManifestObject(manifest);
    const mappings =
      manifest && typeof manifest.mappings === "object" && manifest.mappings !== null
        ? manifest.mappings
        : {};
    for (const [k, v] of Object.entries(mappings)) {
      if (typeof v !== "string") continue;
      classToUtilities.set(k, v);
    }
  }

  let cssOwned = false;
  if (fs.existsSync(outputCssPath)) {
    const cssText = safeReadText(outputCssPath);
    if (cssText !== null) {
      cssOwned = stylesheetIsOwned(cssText, manifest);
      const fromCss = parseExistingStylesheet(cssText);
      for (const [k, v] of fromCss.entries()) {
        if (!classToUtilities.has(k)) {
          classToUtilities.set(k, v);
        }
      }
    }
  }

  // Manifest/dictionary content is repository-supplied: drop entries that are not
  // valid class names or whose expansion would corrupt markup.
  for (const key of Array.from(classToUtilities.keys())) {
    if (!isValidClassIdentifier(key) || !isSafeExpansion(classToUtilities.get(key))) {
      classToUtilities.delete(key);
    }
  }

  if (classToUtilities.size === 0) {
    throw new Error(
      `No TailClass manifest (${path.basename(manifestPath)}) or stylesheet (${path.basename(outputCssPath)}) found to revert from.`
    );
  }

  const { findFiles } = require("./glob");
  const candidateFiles =
    options.filesScanned ||
    findFiles(absRoot, {
      include: config.include,
      exclude: config.exclude,
    });

  const scannedPaths = new Set(candidateFiles.map((f) => toPosixPath(f)));
  const filesReverted = [];
  let totalReverted = 0;

  for (const relFile of candidateFiles) {
    const fullPath = path.join(absRoot, relFile);
    if (!fs.existsSync(fullPath)) continue;
    const source = fs.readFileSync(fullPath, "utf8");
    if (source.includes("\u0000")) continue;

    const rev = revertSource(source, relFile, classToUtilities, config);
    if (!rev.changed) continue;

    filesReverted.push(rev);
    totalReverted += rev.revertedCount;

    if (!dryRun) {
      writeFileNoFollow(fullPath, rev.output);
    }
  }

  const cleanedFiles = [];
  const cleanupSkipped = [];

  if (!dryRun && clean) {
    /** @type {Array<{ target: string, key: string, label: string, owned: boolean, config: object }>} */
    const targets = [
      { target: manifestPath, key: "manifestFile", label: "manifest", owned: manifestOwned, config },
      { target: outputCssPath, key: "outputCss", label: "stylesheet", owned: cssOwned, config },
    ];

    // `apply` records the paths it wrote. If the config changed afterwards, the
    // recorded paths still let `--clean` remove the real generated files instead
    // of leaving them behind (or deleting whatever the new config points at).
    const confinedConfig = (key) => ({
      ...config,
      pathSources: { ...(config.pathSources || {}), [key]: "config" },
    });
    const resolveRecorded = (raw, key) => {
      if (typeof raw !== "string" || raw.trim() === "" || raw.includes("\u0000")) return null;
      try {
        return resolveWritablePath(absRoot, raw, key, confinedConfig(key));
      } catch {
        return null; // hostile/legacy recorded path is ignored, never followed
      }
    };

    if (manifestOwned) {
      const recordedCss = resolveRecorded(manifest.outputCss, "outputCss");
      if (recordedCss && recordedCss !== outputCssPath) {
        targets.push({
          target: recordedCss,
          key: "outputCss",
          label: "stylesheet recorded in the manifest",
          owned: stylesheetIsOwned(safeReadText(recordedCss), manifest),
          config: confinedConfig("outputCss"),
        });
      }
      const recordedManifest = resolveRecorded(manifest.manifestPath, "manifestFile");
      if (recordedManifest && recordedManifest !== manifestPath) {
        let recordedText = safeReadText(recordedManifest);
        let recordedJson = null;
        try {
          recordedJson = recordedText === null ? null : JSON.parse(recordedText);
        } catch {
          recordedJson = null;
        }
        targets.push({
          target: recordedManifest,
          key: "manifestFile",
          label: "manifest recorded in the manifest",
          owned: isTailClassManifestObject(recordedJson),
          config: confinedConfig("manifestFile"),
        });
      }
    }

    const seen = new Set();
    for (const entry of targets) {
      if (seen.has(entry.target)) continue;
      seen.add(entry.target);
      // `--clean` must never remove a file TailClass is scanning/rewriting,
      // even if a hostile config points an output path at it.
      if (scannedPaths.has(toPosixPath(path.relative(absRoot, entry.target)))) {
        cleanupSkipped.push(
          `Refusing to delete ${entry.label} ${entry.target}: it is a scanned source file; left untouched`
        );
        continue;
      }
      if (!entry.owned) {
        cleanupSkipped.push(
          `Refusing to delete ${entry.label} ${entry.target}: it does not look like TailClass output; left untouched`
        );
        continue;
      }
      try {
        const { removed, reason } = unlinkResolvedFile(
          absRoot,
          entry.target,
          entry.key,
          entry.config,
          entry.label
        );
        if (removed) cleanedFiles.push(entry.target);
        else if (reason) cleanupSkipped.push(reason);
      } catch (err) {
        cleanupSkipped.push(`left ${entry.label} ${entry.target} untouched: ${err.message}`);
      }
    }
  }

  return {
    dryRun,
    filesReverted,
    totalFilesReverted: filesReverted.length,
    totalReverted,
    classesExpanded: Array.from(classToUtilities.keys()),
    cleanedFiles,
    cleanupSkipped,
  };
}

